def test_breakdown_table_is_the_ruled_cross_product() -> None:
    """The written rows are the ruled cross product, once each."""
    subjects = {row[0] for row in _TABLE}
    breakdowns = {row[1] for row in _TABLE}
    provenances = {row[2] for row in _TABLE}
    metrics = {row[3] for row in _TABLE}
    keys = {(row[0], row[1], row[2], row[3]) for row in _TABLE}
    assert subjects == {
        "area",
        "place_public",
        "fdi_project",
        "register_company",
        "district",
        "municipality",
        "sector",
        "national",
        "scenario",
    }
    assert subjects == SUBJECTS
    assert breakdowns >= BREAKDOWNS
    assert breakdowns - BREAKDOWNS == {"widget", "age", "SEX"}
    assert provenances == {("public",), ("simulated",), ("public", "simulated")}
    assert metrics == {_GRID, _OTHER}
    assert len(keys) == len(_TABLE)
    assert len(_TABLE) == (
        len(subjects) * len(breakdowns) * len(provenances) * len(metrics)
    )
    assert [row[4] for row in _TABLE].count(None) == 77
    assert [row[4] for row in _TABLE].count(_R) == 409


