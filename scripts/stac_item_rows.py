"""Offline reviewed STAC rows from a pinned collection; no guessed addresses.

The lead must supply the observed filename regex with a named ``part`` group.
No filename default is asserted by this fixture-only implementation.
"""

from __future__ import annotations

import argparse
import ast
import json
import re
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any, cast
from urllib.parse import urljoin

import yaml

from eii_custodian.publicdata.fetch.allowlist import reviewed_url
from eii_custodian.publicdata.fetch.receipts import sha256_hex
from eii_custodian.publicdata.fetch.registry import (
    load_registry,
    read_yaml,
    registry_path,
)
from eii_custodian.publicdata.fetch.snapshots import read_snapshot, reviewed_selections
from eii_custodian.publicdata.heights.model import unique_json

COLLECTION = "bldg_ovt/stac-collection"
COMPONENTS = Path("custodian/src/eii_custodian/publicdata/assembly_sources.py")
TERMS = (
    "licence_id",
    "licence_basis",
    "licence_url",
    "decision_record",
    "terms_url",
    "terms_words",
    "terms_read_on",
    "terms_watch",
)
_BLOCK = re.compile(r"(?m)^  - key: (.+)\n(?:^(?:    .*)?\n)*")


def _row(registry: Sequence[dict[str, Any]], key: str) -> dict[str, Any]:
    matches = [row for row in registry if row["key"] == key]
    if len(matches) != 1:
        raise ValueError("stac_registry_row_missing")
    return matches[0]


def _links(body: bytes, pin: str) -> list[Any]:
    if sha256_hex(body) != pin:
        raise ValueError("stac_collection_hash")
    document = unique_json(body, "stac_collection_json")
    if not isinstance(document, dict):
        raise ValueError("stac_collection_object")
    links = document.get("links")
    if not isinstance(links, list):
        raise ValueError("stac_collection_links")
    return links


def _item(link: dict[str, Any], collection_url: str, pattern: str) -> tuple[str, str]:
    href = link.get("href")
    if not isinstance(href, str):
        raise ValueError("stac_item_href")
    url = urljoin(collection_url, href)
    if not reviewed_url(url):
        raise ValueError("stac_item_host")
    folder = collection_url.rsplit("/", 1)[0] + "/"
    match = re.fullmatch(re.escape(folder) + "(?:" + pattern + ")", url)
    part = match.groupdict().get("part", "") if match else ""
    if re.fullmatch(r"[0-9]{5}", part) is None:
        raise ValueError("stac_item_shape")
    return "bldg_ovt/stac-part-" + part, url


def generate(
    body: bytes, pin: str, registry: Sequence[dict[str, Any]], pattern: str
) -> list[dict[str, Any]]:
    """Copy the collection template and root terms, preserving observed addresses."""
    links = _links(body, pin)
    root, template = _row(registry, "bldg_ovt"), _row(registry, COLLECTION)
    if any(template.get(field) != root.get(field) for field in TERMS):
        raise ValueError("stac_collection_terms")
    output: dict[str, dict[str, Any]] = {}
    for link in links:
        if not isinstance(link, dict):
            raise ValueError("stac_link_object")
        if link.get("rel") in {"next", "child"}:
            raise ValueError("stac_collection_pagination")
        if link.get("rel") != "item":
            continue
        key, url = _item(link, template["url"], pattern)
        if any(row["url"] == url and row["key"] != key for row in registry) or any(
            row["url"] == url for row in output.values()
        ):
            raise ValueError("stac_item_url_collision")
        if key in output:
            raise ValueError("stac_item_key_duplicate")
        row = dict(template)
        row.update({field: root[field] for field in TERMS if field in root})
        row.update(
            key=key,
            url=url,
            landing_url=url,
            skip_reason="",
            title_en=template["title_en"].removesuffix("collection")
            + key.split("stac-", 1)[1],
            basis_note=f"Generated by scripts/stac_item_rows.py from collection SHA-256 {pin}. Decision 0077 item 2.",
        )
        output[key] = row
    if not output:
        raise ValueError("stac_collection_no_items")
    return [output[key] for key in sorted(output)]


def check_rows(
    registry: Sequence[dict[str, Any]], generated: list[dict[str, Any]]
) -> None:
    """Exact field and key equality; placeholders and stale output both refuse."""
    committed = [
        row for row in registry if row["key"].startswith("bldg_ovt/stac-part-")
    ]
    if sorted(committed, key=lambda row: row["key"]) != generated:
        raise ValueError("stac_item_committed_drift")


def replace_rows(text: str, generated: list[dict[str, Any]]) -> str:
    """Replace placeholders in their section, retaining all unrelated source text."""
    emitted = "".join(
        "".join(
            "  " + line + "\n"
            for line in yaml.safe_dump(
                [row], sort_keys=False, allow_unicode=True, width=1000
            ).splitlines()
        )
        for row in generated
    )

    def replace(match: re.Match[str]) -> str:
        key = yaml.safe_load(match[1])
        if key == COLLECTION:
            return match[0] + emitted
        if key.startswith("bldg_ovt/stac-part-"):
            return ""
        return match[0]

    return _BLOCK.sub(replace, text)


def _assignment(text: str) -> ast.AnnAssign:
    for node in ast.parse(text).body:
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            if node.target.id == "BLDG_OVT_KEYS":
                return node
    raise ValueError("stac_component_assignment")


def read_keys(text: str) -> tuple[str, ...]:
    """Read the literal closed tuple without importing possibly stale bytecode."""
    value = _assignment(text).value
    if value is None:
        raise ValueError("stac_component_assignment")
    return tuple(ast.literal_eval(value))


def replace_keys(text: str, keys: tuple[str, ...]) -> str:
    node = _assignment(text)
    lines = text.splitlines(keepends=True)
    block = (
        "BLDG_OVT_KEYS: tuple[str, ...] = (\n"
        + "".join("    " + json.dumps(key) + ",\n" for key in keys)
        + ")\n"
    )
    return "".join(lines[: node.lineno - 1]) + block + "".join(lines[node.end_lineno :])


def run(
    cache: Path, registry: Path, components: Path, pattern: str, *, check: bool
) -> None:
    """Lead-only write/check of reviewed registry records and their closed keys."""
    load_registry(registry)
    # load_registry has validated this same document.
    document = cast(dict[str, Any], read_yaml(registry))
    source_rows = document["sources"]
    identity = reviewed_selections(cache).get(COLLECTION)
    if identity is None:
        raise ValueError("stac_collection_unpinned")
    snapshot = read_snapshot(cache / COLLECTION, identity)
    generated = generate(snapshot.body, identity, source_rows, pattern)
    registry_text, component_text = registry.read_text(), components.read_text()
    replaced = replace_rows(registry_text, generated)
    parsed = yaml.safe_load(replaced)["sources"]
    keys = tuple(sorted(row["key"] for row in parsed if row["source_id"] == "bldg_ovt"))
    if check:
        check_rows(source_rows, generated)
        if read_keys(component_text) != keys:
            raise ValueError("stac_component_keys_drift")
    else:
        updated_components = replace_keys(component_text, keys)
        registry.write_text(replaced, encoding="utf-8")
        components.write_text(updated_components, encoding="utf-8")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("cache", type=Path)
    parser.add_argument("--registry", type=Path, default=registry_path())
    parser.add_argument("--components", type=Path, default=COMPONENTS)
    parser.add_argument("--item-name-pattern", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        run(
            args.cache,
            args.registry,
            args.components,
            args.item_name_pattern,
            check=args.check,
        )
    except (OSError, ValueError, re.error):
        print("stac_item_rows: registry_refused", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
