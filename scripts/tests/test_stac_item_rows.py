def test_new_rows_are_inserted_and_other_bytes_are_unchanged(tmp_path: Path) -> None:
    generated = generate(collection(["00000", "00288", "00384", "00385", "99999"]))
    original = registry_path().read_text()
    changed = rows.replace_rows(original, generated)
    path = tmp_path / "generated.yaml"
    path.write_text(changed)
    document = read_yaml(path)
    assert isinstance(document, dict)
    rows.check_rows(document["sources"], generated)
    # Normalize only the item rows: every other byte must be preserved.
    assert rows.replace_rows(original, []) == rows.replace_rows(changed, [])


