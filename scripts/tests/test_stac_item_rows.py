# Invented filenames, explicitly supplied; no assertion about the real filenames.
PATTERN = r"syn-part-(?P<part>[0-9]{5})-[ab]\.json"
FOLDER = "https://stac.overturemaps.org/2026-10-21.0/buildings/building/"
NUMBERS = ("00288", "00384", "00385")


def registry_rows() -> list[dict[str, Any]]:
    document = read_yaml(registry_path())
    assert isinstance(document, dict)
    result: list[dict[str, Any]] = document["sources"]
    return result


def collection(numbers: Any = NUMBERS) -> dict[str, Any]:
    return {
        "type": "Collection",
        "links": [
            {
                "rel": "item",
                "href": FOLDER + f"syn-part-{number}-a.json",
                "type": "application/geo+json",
            }
            for number in numbers
        ],
    }


def generate(
    document: Any = None,
    registry: Any = None,
    pin: str | None = None,
    pattern: str = PATTERN,
) -> list[dict[str, Any]]:
    body = json.dumps(collection() if document is None else document).encode()
    return rows.generate(
        body,
        sha256_hex(body) if pin is None else pin,
        registry_rows() if registry is None else registry,
        pattern,
    )


def test_rows_equal_template_field_for_field() -> None:
    registry = registry_rows()
    template = next(row for row in registry if row["key"] == rows.COLLECTION)
    output = generate(registry=registry)
    assert len(output) == 3
    digest = sha256_hex(json.dumps(collection()).encode())
    for row, number in zip(output, NUMBERS, strict=True):
        expected = dict(
            template,
            key="bldg_ovt/stac-part-" + number,
            title_en="Overture buildings release 2026-10-21.0 STAC part-" + number,
            url=FOLDER + f"syn-part-{number}-a.json",
            landing_url=FOLDER + f"syn-part-{number}-a.json",
            skip_reason="",
            basis_note=f"Generated by scripts/stac_item_rows.py from collection SHA-256 {digest}. Decision 0077 item 2.",
        )
        assert row == expected
        assert "proposed" not in row["basis_note"]


@pytest.mark.parametrize(
    "case,reason",
    [
        ("hash", "stac_collection_hash"),
        ("missing-links", "stac_collection_links"),
        ("links-type", "stac_collection_links"),
        ("link-object", "stac_link_object"),
        ("href", "stac_item_href"),
        ("host", "stac_item_host"),
        ("shape", "stac_item_shape"),
        ("collection-link", "stac_item_shape"),
        ("no-digits", "stac_item_shape"),
        ("registry-url", "stac_item_url_collision"),
        ("generated-url", "stac_item_url_collision"),
        ("key", "stac_item_key_duplicate"),
        ("next", "stac_collection_pagination"),
        ("child", "stac_collection_pagination"),
        ("no-item", "stac_collection_no_items"),
        ("licence", "stac_collection_terms"),
        ("root", "stac_collection_object"),
        ("required-row", "stac_registry_row_missing"),
    ],
)
def test_each_refusal(case: str, reason: str) -> None:
    document: Any = collection()
    registry = registry_rows()
    pin = None
    if case == "hash":
        pin = "a" * 64
    elif case == "missing-links":
        del document["links"]
    elif case == "links-type":
        document["links"] = {}
    elif case == "link-object":
        document["links"][0] = "SYN bad object"
    elif case == "href":
        document["links"][0]["href"] = None
    elif case == "host":
        document["links"][0]["href"] = document["links"][0]["href"].replace(
            "stac.overturemaps.org", "syn.invalid"
        )
    elif case in {"shape", "collection-link", "no-digits"}:
        document["links"][0]["href"] = (
            FOLDER
            + {
                "shape": "other/syn-part-00288-a.json",
                "collection-link": "collection.json",
                "no-digits": "syn-part-a.json",
            }[case]
        )
    elif case == "registry-url":
        registry[0]["url"] = document["links"][0]["href"]
    elif case == "generated-url":
        document["links"].append(copy.deepcopy(document["links"][0]))
    elif case == "key":
        link = dict(document["links"][0])
        link["href"] = link["href"].replace("-a.json", "-b.json")
        document["links"].append(link)
    elif case in {"next", "child"}:
        document["links"].append(
            {"rel": case, "href": FOLDER + "page.json", "type": "application/json"}
        )
    elif case == "no-item":
        document["links"] = []
    elif case == "licence":
        next(row for row in registry if row["key"] == rows.COLLECTION)["licence_id"] = (
            "SYN changed"
        )
    elif case == "root":
        document = []
    elif case == "required-row":
        registry = [row for row in registry if row["key"] != rows.COLLECTION]
    with pytest.raises(ValueError, match=r"^" + reason + "$"):
        generate(document, registry, pin)


def test_check_and_placeholder_replacement(tmp_path: Path) -> None:
    original = registry_path().read_text()
    generated = generate()
    document = rows.replace_rows(original, generated)
    path = tmp_path / "sources.yaml"
    path.write_text(document)
    loaded = read_yaml(path)
    assert isinstance(loaded, dict)
    committed = loaded["sources"]
    rows.check_rows(committed, generated)
    for field in generated[0]:
        changed = copy.deepcopy(committed)
        next(row for row in changed if row["key"] == generated[0]["key"])[field] = (
            "SYN drift"
        )
        with pytest.raises(ValueError, match=r"^stac_item_committed_drift$"):
            rows.check_rows(changed, generated)
    for changed in (
        [*committed, dict(generated[0], key="bldg_ovt/stac-part-99999")],
        [row for row in committed if row["key"] != generated[0]["key"]],
    ):
        with pytest.raises(ValueError, match=r"^stac_item_committed_drift$"):
            rows.check_rows(changed, generated)
    assert rows.replace_rows(document, generated) == document
    # Own committed output is allowed by the different-key collision rule R1.
    assert generate(registry=committed) == generated
    old = {row["key"]: row for row in registry_rows()}
    new = {row["key"]: row for row in committed}
    for key in old.keys() - {row["key"] for row in generated}:
        assert old[key] == new[key]


def test_component_assignment_roundtrip() -> None:
    path = Path("custodian/src/eii_custodian/publicdata/assembly_sources.py")
    text = path.read_text()
    keys = ("bldg_ovt", "bldg_ovt/stac-part-99999")
    updated = rows.replace_keys(text, keys)
    assert rows.read_keys(updated) == keys
    assert rows.replace_keys(updated, keys) == updated
    with pytest.raises(ValueError, match=r"^stac_component_assignment$"):
        rows.read_keys("SYN = ()\n")


@given(
    st.lists(
        st.integers(min_value=0, max_value=99999), min_size=1, max_size=15, unique=True
    )
)
def test_order_independence_and_injective_key_property(numbers: list[int]) -> None:
    names = [f"{number:05d}" for number in numbers]
    output = generate(collection(names))
    assert [{k: v for k, v in row.items() if k != "basis_note"} for row in output] == [
        {k: v for k, v in row.items() if k != "basis_note"}
        for row in generate(collection(list(reversed(names))))
    ]
    assert {row["key"].rsplit("-", 1)[1] for row in output} == set(names)
    assert len(output) == len(names)
    assert all(row["landing_url"] == row["url"] for row in output)


def fixture_run(tmp_path: Path) -> tuple[Path, Path, Path]:
    from test_stac_item_pins import store

    from eii_custodian.publicdata.fetch.registry import load_registry

    registry = tmp_path / "sources.yaml"
    registry.write_text(registry_path().read_text())
    components = tmp_path / "assembly_sources.py"
    components.write_text(rows.COMPONENTS.read_text())
    cache = tmp_path / "cache"
    entry = next(row for row in load_registry(registry) if row.key == rows.COLLECTION)
    digest = store(cache, entry, json.dumps(collection()).encode())
    (cache / "snapshot_pins.json").write_text(json.dumps({entry.key: digest}))
    return cache, registry, components


def test_run_write_then_check_and_cli_refusal(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    cache, registry, components = fixture_run(tmp_path)
    args = [
        str(cache),
        "--registry",
        str(registry),
        "--components",
        str(components),
        "--item-name-pattern",
        PATTERN,
    ]
    assert rows.main([*args, "--check"]) == 1
    assert capsys.readouterr().err == "stac_item_rows: registry_refused\n"
    assert rows.main(args) == 0
    original = (registry.read_bytes(), components.read_bytes())
    assert rows.main([*args, "--check"]) == 0
    assert original == (registry.read_bytes(), components.read_bytes())
    # Every other source and forecast section survives the textual records edit.
    old = read_yaml(registry_path())
    new = read_yaml(registry)
    assert isinstance(old, dict) and isinstance(new, dict)
    assert old["forecast_series"] == new["forecast_series"]
    assert [r for r in old["sources"] if r["source_id"] != "bldg_ovt"] == [
        r for r in new["sources"] if r["source_id"] != "bldg_ovt"
    ]


