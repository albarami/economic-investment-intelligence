"""Static import-boundary guard over the three package source trees."""

from __future__ import annotations

import ast
import errno
import os
from pathlib import Path

PACKAGES = (
    ("eii_core", "core/src/eii_core"),
    ("eii_custodian", "custodian/src/eii_custodian"),
    ("eii_product", "product/src/eii_product"),
)
FORBIDDEN = {
    "eii_core": ("eii_custodian", "eii_product", "eii_gateway"),
    "eii_custodian": ("eii_product", "eii_gateway"),
    "eii_product": ("eii_custodian", "eii_gateway"),
}
ENV_NAMES = ("EII_DECISION_PROVIDER", "JEV_PRO_API_KEY", "EARTHDATA_API_KEY")
BYTECODE_DIR = "__pycache__"


def read_file(path: Path) -> bytes:
    """Return the raw bytes of a repository file."""
    return path.read_bytes()


def is_exempt_bytecode(path: Path) -> bool:
    """Return whether ``path`` is generated bytecode exempt from env-name search."""
    return path.suffix == ".pyc" and path.parent.name == BYTECODE_DIR


def _rel_posix(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def _sort_key(line: str) -> tuple[str, int, str]:
    """Sort key as (path, line number, full line text)."""
    if line.startswith(("FAIL ", "NOTE ")):
        body = line.split(" ", 1)[1]
        _rule, _, rest = body.partition(": ")
        if not rest:
            return (line, 0, line)
        segments = rest.split(":", 2)
        if len(segments) >= 2 and segments[1].isdigit():
            return (segments[0], int(segments[1]), line)
        return (segments[0], 0, line)
    return (line, 0, line)


def _group_and_sort(
    failures: list[str], notes: list[str]
) -> tuple[list[str], list[str]]:
    rule_order = (
        "src-tree",
        "symlink",
        "unparsable",
        "relative-escape",
        "forbidden-import",
        "env-name",
    )

    def rule_of(line: str) -> str:
        if line.startswith("FAIL "):
            return line.split(":", 1)[0][5:]
        if line.startswith("NOTE "):
            return "note"
        return ""

    grouped: dict[str, list[str]] = {r: [] for r in rule_order}
    grouped["note"] = []
    for line in failures:
        grouped[rule_of(line)].append(line)
    for line in notes:
        grouped["note"].append(line)
    out_fail: list[str] = []
    for rule in rule_order:
        items = sorted(set(grouped[rule]), key=_sort_key)
        out_fail.extend(items)
    out_notes = sorted(set(grouped["note"]), key=_sort_key)
    return out_fail, out_notes


def check_imports(root: Path) -> tuple[list[str], list[str]]:
    """Scan the three source trees under ``root`` for import-boundary violations.

    Args:
        root: Repository root containing ``core/``, ``custodian/`` and ``product/``.

    Returns:
        Sorted failure lines and sorted note lines.
    """
    import import_boundary_judge as judge

    failures: list[str] = []
    notes: list[str] = []
    seen_fail: set[str] = set()
    seen_note: set[str] = set()

    def add_fail(line: str) -> None:
        if line not in seen_fail:
            seen_fail.add(line)
            failures.append(line)

    def add_note(line: str) -> None:
        if line not in seen_note:
            seen_note.add(line)
            notes.append(line)

    for package, rel in PACKAGES:
        tree = root / rel
        rel_path = rel.replace("\\", "/")
        ancestor = root
        for part in Path(rel).parts:
            ancestor = ancestor / part
            if os.path.islink(ancestor):
                add_fail(
                    f"FAIL symlink: {_rel_posix(root, ancestor)}: "
                    "symbolic link under a source tree"
                )
                break
        else:
            if not tree.is_dir():
                add_fail(f"FAIL src-tree: {rel_path}: missing or not a directory")
                continue
            py_found = False

            def onerror(exc: OSError) -> None:
                path = getattr(exc, "filename", None)
                if path is None:
                    return
                rel_p = _rel_posix(root, Path(path))
                err_no = exc.errno
                if err_no is not None and err_no in errno.errorcode:
                    name = errno.errorcode[err_no]
                else:
                    name = "OSError"
                add_fail(f"FAIL unparsable: {rel_p}: cannot be read ({name})")

            for dirpath, dirnames, filenames in os.walk(
                tree, followlinks=False, onerror=onerror
            ):
                dirnames.sort()
                filenames.sort()
                cur = Path(dirpath)
                kept_dirs: list[str] = []
                for name in dirnames:
                    p = cur / name
                    if os.path.islink(p):
                        add_fail(
                            f"FAIL symlink: {_rel_posix(root, p)}: "
                            "symbolic link under a source tree"
                        )
                    else:
                        kept_dirs.append(name)
                dirnames[:] = kept_dirs
                for name in filenames:
                    path = cur / name
                    if os.path.islink(path):
                        add_fail(
                            f"FAIL symlink: {_rel_posix(root, path)}: "
                            "symbolic link under a source tree"
                        )
                        continue
                    rel_file = _rel_posix(root, path)
                    try:
                        data = read_file(path)
                    except OSError as exc:
                        err_no = exc.errno
                        if err_no is not None and err_no in errno.errorcode:
                            name_err = errno.errorcode[err_no]
                        else:
                            name_err = "OSError"
                        add_fail(
                            f"FAIL unparsable: {rel_file}: cannot be read ({name_err})"
                        )
                        continue
                    if not is_exempt_bytecode(path):
                        for env_name in ENV_NAMES:
                            if (
                                env_name == "EARTHDATA_API_KEY"
                                and package == "eii_custodian"
                            ):
                                continue
                            if env_name.encode() in data:
                                lines = data.split(b"\n")
                                for idx, row in enumerate(lines, start=1):
                                    if env_name.encode() in row:
                                        add_fail(
                                            f"FAIL env-name: {rel_file}:{idx}: "
                                            f"contains {env_name}"
                                        )
                                        break
                    if path.name.endswith(".py"):
                        py_found = True
                        parts = [package, *path.relative_to(tree).parent.parts]
                        try:
                            tree_ast = ast.parse(data, rel_file)
                        except (
                            SyntaxError,
                            ValueError,
                            RecursionError,
                            MemoryError,
                        ) as exc:
                            add_fail(
                                f"FAIL unparsable: {rel_file}: cannot be parsed "
                                f"({type(exc).__name__})"
                            )
                            continue
                        hits = judge.judge_tree(
                            tree_ast, package, parts, FORBIDDEN[package]
                        )
                        for hit in hits:
                            if hit.kind == "dynamic-import":
                                msg = (
                                    f"NOTE dynamic-import: {rel_file}:{hit.line}: "
                                    f"{hit.form} argument cannot be resolved statically"
                                )
                                add_note(msg)
                            elif hit.kind == "relative-escape":
                                add_fail(
                                    f"FAIL relative-escape: {rel_file}:{hit.line}: "
                                    "relative import goes beyond its top-level package"
                                )
                            elif hit.kind == "forbidden-import":
                                forb = hit.target.split(".")[0]
                                add_fail(
                                    f"FAIL forbidden-import: {rel_file}:{hit.line}: "
                                    f"{hit.form} {hit.target} ({package} -> {forb})"
                                )
            if not py_found:
                add_fail(f"FAIL src-tree: {rel_path}: no Python file")

    return _group_and_sort(failures, notes)
